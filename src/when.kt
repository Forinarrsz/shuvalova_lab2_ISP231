fun main() {
    val number = readln().toInt()
    val month = when (number) {
        1 -> "январь"
        2 -> "февраль"
        3 -> "март"
        4 -> "апрель"
        5 -> "май"
        6 -> "июнь"
        7 -> "июль"
        8 -> "август"
        9 -> "сентябрь"
        10 -> "октябрь"
        11 -> "ноябрь"
        12 -> "декабрь"
        else -> "нет соответствующего номера"
    }

    if (number in 1..12) {
        println("Вы ввели номер $number, это месяц - $month")
    }
}